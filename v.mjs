import { webkit, devices } from 'playwright-core'
const b = await webkit.launch()
const c = await b.newContext({ ...devices['iPhone 13'] }); const p = await c.newPage()
const errs = []; p.on('pageerror', (e) => errs.push(String(e)))
await p.goto('http://localhost:5173/', { waitUntil: 'networkidle' })
await p.getByText('시작하기', { exact: true }).click(); await p.waitForTimeout(1500)
console.log(p.url())
await p.fill('.vs-start-input', '/e/a8be34a6-230a-4e03-9e59-19a04ff26d8d'); await p.getByText('행사 열기').click(); await p.waitForTimeout(2500)
console.log(p.url(), (await p.innerText('body')).slice(0, 60).replace(/\n/g, ' '), errs)
await b.close()
